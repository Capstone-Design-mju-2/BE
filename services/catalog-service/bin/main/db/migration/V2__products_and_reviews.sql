-- Schema only. Collected data is loaded through the catalog load API, never through migrations.
-- Reviewer identifiers (nickname, user ids, images) are not stored. Height and weight are 5cm/5kg buckets.

CREATE TABLE products (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    external_id     BIGINT       NOT NULL UNIQUE,
    name            VARCHAR(300) NOT NULL,
    brand_name      VARCHAR(100) NOT NULL,
    category_code   VARCHAR(20)  NOT NULL,
    normal_price    INTEGER      NOT NULL,
    price           INTEGER      NOT NULL,
    review_count    INTEGER      NOT NULL,
    review_score    SMALLINT     NOT NULL CHECK (review_score BETWEEN 0 AND 100),
    collected_on    DATE         NOT NULL
);

CREATE TABLE reviews (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id      BIGINT       NOT NULL REFERENCES products (id),
    external_id     BIGINT       NOT NULL UNIQUE,
    content         TEXT         NOT NULL,
    grade           SMALLINT     NOT NULL CHECK (grade BETWEEN 1 AND 5),
    like_count      INTEGER      NOT NULL,
    option_text     VARCHAR(200),
    skin_type       VARCHAR(30),
    skin_tone       VARCHAR(30),
    gender          VARCHAR(10),
    -- NULL bound means an open-ended bucket.
    height_min_cm   SMALLINT,
    height_max_cm   SMALLINT,
    weight_min_kg   SMALLINT,
    weight_max_kg   SMALLINT,
    written_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    collected_on    DATE         NOT NULL
);

CREATE INDEX idx_reviews_product_id ON reviews (product_id);

CREATE TABLE review_survey_answers (
    review_id       BIGINT       NOT NULL REFERENCES reviews (id),
    attribute       VARCHAR(50)  NOT NULL,
    answer          VARCHAR(50)  NOT NULL,
    PRIMARY KEY (review_id, attribute, answer)
);
